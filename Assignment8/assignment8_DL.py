import numpy as np
import torch
import os
import matplotlib.pyplot as plt
import seaborn as sns

from datasets import load_dataset
from transformers import (
    AutoTokenizer,
    AutoModelForSequenceClassification,
    Trainer,
    TrainingArguments
)

from sklearn.metrics import (
    accuracy_score,
    precision_recall_fscore_support,
    classification_report,
    confusion_matrix
)

print("Device:", "cuda" if torch.cuda.is_available() else "cpu")

dataset = load_dataset("fancyzhx/ag_news")

train_ds = dataset["train"].shuffle(seed=42).select(range(5000))
test_ds = dataset["test"].shuffle(seed=42).select(range(1000))

print("Training examples:", len(train_ds))
print("Testing examples:", len(test_ds))

print("\nExample news:")
print(train_ds[0]["text"])

print("\nLabel:", train_ds[0]["label"])

model_name = "distilbert-base-uncased"

tokenizer = AutoTokenizer.from_pretrained(model_name)

def tokenize(data):
    return tokenizer(
        data["text"],
        truncation=True,
        padding="max_length",
        max_length=128
    )

train_ds = train_ds.map(tokenize, batched=True)
test_ds = test_ds.map(tokenize, batched=True)

print("Tokenization completed.")

model = AutoModelForSequenceClassification.from_pretrained(
    model_name,
    num_labels=4
)

print("Model loaded.")

def metrics(eval_pred):
    logits, labels = eval_pred
    predictions = np.argmax(logits, axis=1)

    precision, recall, f1, _ = precision_recall_fscore_support(
        labels,
        predictions,
        average="weighted",
        zero_division=0
    )

    accuracy = accuracy_score(labels, predictions)

    return {
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1": f1
    }

training_args = TrainingArguments(
    output_dir="./results",
    num_train_epochs=4,
    per_device_train_batch_size=8,
    per_device_eval_batch_size=16,
    learning_rate=2e-5,
    eval_strategy="epoch",
    save_strategy="epoch",
    save_total_limit=1,
    report_to="none"
)

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_ds,
    eval_dataset=test_ds,
    processing_class=tokenizer,
    compute_metrics=metrics
)

print("Trainer created successfully.")

trainer.train()

trainer.save_model("./final_model")
tokenizer.save_pretrained("./final_model")

print("Model saved successfully.")
print(os.listdir("./final_model"))

results = trainer.evaluate()

print("Evaluation Results")
print("-" * 40)

for key, value in results.items():
    if isinstance(value, (float, np.floating)):
        print(f"{key}: {value:.4f}")
    else:
        print(f"{key}: {value}")

pred = trainer.predict(test_ds)

predictions = np.argmax(
    pred.predictions,
    axis=1
)

true_labels = pred.label_ids

categories = [
    "WORLD",
    "SPORTS",
    "BUSINESS",
    "SCI/TECH"
]

print(
    classification_report(
        true_labels,
        predictions,
        labels=[0, 1, 2, 3],
        target_names=categories,
        digits=4,
        zero_division=0
    )
)

cm = confusion_matrix(
    true_labels,
    predictions,
    labels=[0, 1, 2, 3]
)

print("Confusion Matrix:")
print(cm)

plt.figure(figsize=(7, 5))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=categories,
    yticklabels=categories
)

plt.title("DistilBERT - AG News Confusion Matrix")
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.tight_layout()
plt.show()

def predict_news(text):
    model.eval()

    inputs = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        padding=True,
        max_length=128
    )

    inputs = {
        key: value.to(model.device)
        for key, value in inputs.items()
    }

    with torch.no_grad():
        output = model(**inputs)

    prediction = torch.argmax(
        output.logits,
        dim=1
    ).item()

    categories = [
        "WORLD",
        "SPORTS",
        "BUSINESS",
        "SCI/TECH"
    ]

    return categories[prediction]

test_news = [
    "India won the cricket match against Australia.",
    "The company announced a new business deal.",
    "Scientists developed a new artificial intelligence system.",
    "World leaders met to discuss international relations."
]

for news in test_news:
    print("News:", news)
    print("Category:", predict_news(news))
    print("-" * 50)