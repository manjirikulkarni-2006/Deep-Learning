import numpy as np
import tensorflow as tf
import os

from tensorflow.keras.preprocessing.image import ImageDataGenerator
from tensorflow.keras.preprocessing import image
from tensorflow.keras.layers import Flatten, Dense, Dropout, Conv2D, MaxPooling2D
from tensorflow.keras.applications import ResNet50
import matplotlib.pyplot as plt

url = "https://storage.googleapis.com/download.tensorflow.org/example_images/flower_photos.tgz"

dataset_path = tf.keras.utils.get_file(
    "flower_photos",
    origin=url,
    untar=True
)

folder_path = dataset_path + "/flower_photos"

print("Dataset downloaded!")

print("Total daisy images:", len(os.listdir(folder_path + "/daisy")))
print("Total dandelion images:", len(os.listdir(folder_path + "/dandelion")))
print("Total roses images:", len(os.listdir(folder_path + "/roses")))
print("Total sunflowers images:", len(os.listdir(folder_path + "/sunflowers")))
print("Total tulips images:", len(os.listdir(folder_path + "/tulips")))

fig = plt.figure(figsize=(10, 7))

classes = ["daisy", "dandelion", "roses", "sunflowers", "tulips"]

for i, cls in enumerate(classes):
    img_name = os.listdir(folder_path + "/" + cls)[0]
    img = image.load_img(folder_path + "/" + cls + "/" + img_name)

    fig.add_subplot(2, 3, i + 1)
    plt.imshow(img)
    plt.title(cls)
    plt.axis("off")

plt.show()

train_datagen = ImageDataGenerator(
    fill_mode="nearest",
    validation_split=0.2
)

train_generator = train_datagen.flow_from_directory(
    folder_path,
    target_size=(108, 108),
    color_mode="rgb",
    class_mode="categorical",
    subset="training"
)

validation_generator = train_datagen.flow_from_directory(
    folder_path,
    target_size=(108, 108),
    color_mode="rgb",
    class_mode="categorical",
    subset="validation"
)

model = tf.keras.models.Sequential([
    ResNet50(
        input_shape=(108, 108, 3),
        include_top=False,
        weights="imagenet"
    )
])

for layer in model.layers:
    layer.trainable = False

model.add(Conv2D(64, (3,3), activation="relu"))
model.add(MaxPooling2D(2,2))
model.add(Flatten())
model.add(Dense(64, activation="relu"))
model.add(Dropout(0.4))
model.add(Dense(5, activation="softmax"))

model.summary()

model.compile(
    optimizer="Adam",
    loss="categorical_crossentropy",
    metrics=["accuracy"]
)

history = model.fit(
    train_generator,
    validation_data=validation_generator,
    epochs=10,
    verbose=1
)

plt.plot(history.history["accuracy"], label="Training Accuracy")
plt.plot(history.history["val_accuracy"], label="Validation Accuracy")
plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.legend()
plt.show()

plt.plot(history.history["loss"], label="Training Loss")
plt.plot(history.history["val_loss"], label="Validation Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()
plt.show()