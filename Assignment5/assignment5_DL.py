# Import libraries for data handling, numerical operations and visualization
import kagglehub
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import os

# Import preprocessing and evaluation metrics
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score

# Import deep learning models and layers
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import SimpleRNN, LSTM, GRU, Dense

# Download the Gold Price Dataset using KaggleHub
path = kagglehub.dataset_download(
    "rizkykiky/gold-price-dataset"
)

# Display the downloaded dataset folder path
print("Path to dataset files:", path)

# Display all files available in the dataset folder
print("Files in dataset folder:")
print(os.listdir(path))

# Read the Daily.csv file from the downloaded dataset
df = pd.read_csv(
    os.path.join(path, "Daily.csv")
)

# Display the first five records
print(df.head())

# Display column names
print(df.columns)

# Display the number of rows and columns
print(df.shape)

# Convert the Date column into datetime format
df["Date"] = pd.to_datetime(df["Date"])

# Select only Date and INR columns
df = df[["Date", "INR"]]

# Remove rows containing missing values
df = df.dropna()

# Sort records in chronological order
df = df.sort_values("Date")

# Remove commas from gold prices
df["INR"] = df["INR"].str.replace(",", "", regex=False)

# Convert gold prices into numeric format
df["INR"] = pd.to_numeric(
    df["INR"],
    errors="coerce"
)

# Remove rows with invalid gold prices
df = df.dropna(subset=["INR"])

# Display cleaned dataset
print(df.head())

# Display updated dataset dimensions
print(df.shape)

# Plot the historical gold price trend
plt.figure(figsize=(12, 5))

plt.plot(
    df["Date"],
    df["INR"]
)

# Add labels and title
plt.xlabel("Date")
plt.ylabel("Gold Price (INR)")
plt.title("Gold Price Trend")

# Display grid
plt.grid(True)

# Show the graph
plt.show()

# Extract gold prices and reshape into a 2D array
prices = df["INR"].values.reshape(-1, 1)

# Initialize MinMaxScaler
scaler = MinMaxScaler()

# Scale prices between 0 and 1
prices_scaled = scaler.fit_transform(prices)

# Display original and scaled price ranges
print("Original price range:",
      prices.min(), "to", prices.max())

print("Scaled price range:",
      prices_scaled.min(), "to", prices_scaled.max())

# Define the number of previous days used for prediction
sequence_length = 30

# Initialize input and output lists
X = []
y = []

# Create sequences using the previous 30 days
for i in range(
    sequence_length,
    len(prices_scaled)
):

    # Store previous 30 days as input
    X.append(
        prices_scaled[
            i-sequence_length:i
        ]
    )

    # Store the next day's price as target
    y.append(
        prices_scaled[i]
    )

# Convert lists into NumPy arrays
X = np.array(X)
y = np.array(y)

# Display input and output shapes
print("X shape:", X.shape)
print("y shape:", y.shape)

# Use 80% data for training and 20% for testing
train_size = int(len(X) * 0.8)

# Split input data
X_train = X[:train_size]
X_test = X[train_size:]

# Split target data
y_train = y[:train_size]
y_test = y[train_size:]

# Obtain dates corresponding to the testing data
test_dates = df["Date"].iloc[
    sequence_length + train_size:
].reset_index(drop=True)

# Display training and testing dimensions
print("Training data:", X_train.shape)
print("Testing data:", X_test.shape)

# Function to build the selected recurrent neural network model
def build(kind):

    # Initialize Sequential model
    model = Sequential()

    # Build Simple RNN model
    if kind == "RNN":

        model.add(
            SimpleRNN(
                50,
                input_shape=(
                    X_train.shape[1],
                    X_train.shape[2]
                )
            )
        )

    # Build LSTM model
    elif kind == "LSTM":

        model.add(
            LSTM(
                50,
                input_shape=(
                    X_train.shape[1],
                    X_train.shape[2]
                )
            )
        )

    # Build GRU model
    else:

        model.add(
            GRU(
                50,
                input_shape=(
                    X_train.shape[1],
                    X_train.shape[2]
                )
            )
        )

    # Add output layer to predict one gold price
    model.add(Dense(1))

    # Compile model using Adam optimizer and MSE loss
    model.compile(
        optimizer="adam",
        loss="mean_squared_error"
    )

    # Return compiled model
    return model

# Store evaluation results of all models
results = []

# Store predictions of individual models
predictions_dict = {}

# Train and evaluate RNN, LSTM and GRU
for kind in ["RNN", "LSTM", "GRU"]:

    print("\n")
    print(kind)

    # Build the selected model
    model = build(kind)

    # Train the model
    history = model.fit(
        X_train,
        y_train,
        epochs=10,
        batch_size=32,
        validation_split=0.2,
        verbose=1
    )

    # Predict gold prices using testing data
    predictions = model.predict(
        X_test,
        verbose=0
    )

    # Convert scaled predictions into original price values
    predicted_prices = scaler.inverse_transform(
        predictions
    )

    # Convert actual scaled prices into original values
    actual_prices = scaler.inverse_transform(
        y_test
    )

    # Store predictions for comparison
    predictions_dict[kind] = predicted_prices

    # Calculate Mean Absolute Error
    mae = mean_absolute_error(
        actual_prices,
        predicted_prices
    )

    # Calculate Root Mean Squared Error
    rmse = np.sqrt(
        mean_squared_error(
            actual_prices,
            predicted_prices
        )
    )

    # Calculate R2 score
    r2 = r2_score(
        actual_prices,
        predicted_prices
    )

    # Display evaluation metrics
    print("MAE:", mae)
    print("RMSE:", rmse)
    print("R2:", r2)

    # Store model name and evaluation metrics
    results.append([
        kind,
        mae,
        rmse,
        r2
    ])

# Plot actual gold prices against predictions from all three models
plt.figure(figsize=(14, 6))

# Plot actual gold prices
plt.plot(
    test_dates,
    actual_prices.flatten(),
    label="Actual Price"
)

# Plot RNN predictions
plt.plot(
    test_dates,
    predictions_dict["RNN"].flatten(),
    label="RNN Prediction"
)

# Plot LSTM predictions
plt.plot(
    test_dates,
    predictions_dict["LSTM"].flatten(),
    label="LSTM Prediction"
)

# Plot GRU predictions
plt.plot(
    test_dates,
    predictions_dict["GRU"].flatten(),
    label="GRU Prediction"
)

# Add graph labels and title
plt.xlabel("Date")
plt.ylabel("Gold Price (INR)")
plt.title("Actual vs Predicted Gold Prices")

# Display legend and grid
plt.legend()
plt.grid(True)

# Show comparison graph
plt.show()

# Convert evaluation results into a DataFrame
results_df = pd.DataFrame(
    results,
    columns=[
        "Model",
        "MAE",
        "RMSE",
        "R2"
    ]
)

# Display performance comparison table
print(results_df)

# Create a figure for comparing evaluation metrics
plt.figure(figsize=(15, 5))

# MAE Comparison
plt.subplot(1, 3, 1)

plt.bar(
    results_df["Model"],
    results_df["MAE"]
)

plt.title("MAE Comparison")
plt.xlabel("Model")
plt.ylabel("MAE")
plt.grid(axis="y")


# RMSE Comparison
plt.subplot(1, 3, 2)

plt.bar(
    results_df["Model"],
    results_df["RMSE"]
)

plt.title("RMSE Comparison")
plt.xlabel("Model")
plt.ylabel("RMSE")
plt.grid(axis="y")


# R2 Score Comparison
plt.subplot(1, 3, 3)

plt.bar(
    results_df["Model"],
    results_df["R2"]
)

plt.title("R² Comparison")
plt.xlabel("Model")
plt.ylabel("R² Score")
plt.grid(axis="y")


# Add overall title
plt.suptitle(
    "Performance Comparison of RNN, LSTM and GRU",
    fontsize=16
)

# Adjust layout to prevent overlapping
plt.tight_layout()

# Display all comparison graphs
plt.show()